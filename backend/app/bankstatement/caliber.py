"""流水对账这条线**自己的口径**：哪些科目算「钱放的地方」。

**为什么要单开一份**：全系统另有一份「现金类科目」的口径
（``app.accounting.organize.CASH_SUBJECT_PREFIXES``，1001/1002/1012）——
现金流量表、报表、MCP 工具在用，**那里的 1012 确实算货币资金**
（其他货币资金就是钱，现金流量表里当然要算）。

但**流水对账这一条线只认 1002**（2026-10-28 用户定的口径：先说「一定要
排除 1012」「我只会用到 1001 和 1002」，随后又说「1001 没有对账单，可以把
1001 也排除」）：

* **1012 其他货币资金**是第三方支付平台的备付金（支付宝、微信的钱），
  不是银行账户 —— 网银导出的对账单不可能是它。把它列为可绑定的账户，
  只会让用户绑一份永远对不上的对账单；
* **1001 库存现金**也没有对账单 —— 现金是放在抽屉里的，拿网银流水去对
  库存现金对不出任何东西；用户从来没给 1001 绑过对账单。

所以这一线认的「钱放的地方」就是**银行存款（1002）**—— 银行流水本来就是
银行出的，对的当然是银行账户。

**别把这两个口径混了**：改这里的常量**不会**影响现金流量表、报表、MCP
工具；反之亦然。改动只在这一条线内生效。

放在独立模块里还有一个好处：``service`` / ``matching`` / ``suspicious``
三个模块都要用它，而 ``service`` 会 import ``matching`` —— 放 ``service``
里会形成循环导入。
"""
from __future__ import annotations

#: 流水对账认的「钱放的地方」：**1002 银行存款**（含它的明细科目）。
#:
#: **不含 1001 库存现金、不含 1012 其他货币资金** —— 理由见本模块的说明。
CASH_SUBJECT_PREFIXES = ("1002",)

#: 「**自家账户**」的编码前缀：1001 库存现金、1002 银行存款、1012 其他
#: 货币资金 —— 抽屉里的钱、银行里的钱、支付宝里的钱，都是自家的钱。
#:
#: **与上面那个不是一回事**：``CASH_SUBJECT_PREFIXES`` 回答的是「这份对账单
#: 能绑在哪个账户上、拿哪边的分录去跟银行流水对」（只能是银行账户）；
#: ``OWN_MONEY_SUBJECT_PREFIXES`` 回答的是「这笔钱是不是在自家账户之间挪」
#: （抽屉 ↔ 银行 ↔ 支付宝，都是内部转账）。
#:
#: 内部转账的判定必须用这个宽口径：用窄口径的话，取现（借 1001 / 贷 1002）
#: 会被判成「1002 那边对不上流水」—— 凭空多出一堆假存疑。
OWN_MONEY_SUBJECT_PREFIXES = ("1001", "1002", "1012")


def account_subject_code(subject, statement) -> str:
    """界面上显示的那个**科目码**：活科目的码优先，科目行不在了才回落快照。

    **为什么不能直接用快照列**：``bank_statement.account_subject_code`` 是
    「上传那一刻」的副本，而**科目编码是可以改的**（``SubjectEditIn.code``）——
    用户改完码，快照不会跟着变。于是台账上会出现「旧码 + 新名」：
    1001 库存现金 与 100201 银行存款只差一位，肉眼扫过去根本看不出哪里不对
    （实测：dev 库里一份绑在 100201 上的对账单，界面上摆的是「1001」）。

    **名称一直就是取活科目的**（``account_subject_name``），码也该从同一个
    地方来 —— 两边不一致比哪边旧更糟。

    **科目行不在了怎么办**：外键是 RESTRICT，正常路径下删不掉科目行；
    真没了（老数据、或绕过了外键的手工操作）时，快照是「这份对账单当年
    绑的是哪个账户」的唯一线索，不能丢。

    :param subject: 活科目行（``db.get(Subject, statement.account_subject_id)``）
    :param statement: 对账单行
    :returns: 科目码（字符串）
    """
    if subject is not None:
        return subject.code
    return statement.account_subject_code
