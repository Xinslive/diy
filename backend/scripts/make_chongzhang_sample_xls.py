def build(path: Path) -> Path:
    book = xlwt.Workbook(encoding="utf-8")
    sheet = book.add_sheet("Sheet0")

    def put(row: int, values: list[str]) -> None:
        for column, value in enumerate(values):
            # **全部写成文本**：真实文件里金额带千分位（``5,000.00``），
            # 银行导出成文本；日期也是文本。写成数字会改掉容器读出来的东西。
            sheet.write(row, column, value)

    for index, values in enumerate(META_ROWS):
        put(index, values)
    put(len(META_ROWS), HEADER)
    for offset, values in enumerate(ROWS):
        put(len(META_ROWS) + 1 + offset, values)
    put(len(META_ROWS) + 1 + len(ROWS), FOOTER_ROW)

    path.parent.mkdir(parents=True, exist_ok=True)
    book.save(str(path))
    return path


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    print(build(target))
