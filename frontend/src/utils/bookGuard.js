/**
 * 没有账套时，账套相关的页面要不要把人送回账套管理。
 *
 * 这个判断有三个维度，缺一个都会在某个真实场景里出错：
 *
 *  1. **requiresBook** —— 这个页面是不是「没有账套就没法工作」的那类。
 *     系统管理那几页（用户与授权、外部服务、邮件通知、数据安全、扩展管理、
 *     计划任务）是**全站级**的，跟账套无关：管理员自己没有账套时也得进得去，
 *     否则插件和计划任务就没人管了。账套管理页自己也不需要 —— 它就是建账套的地方。
 *
 *  2. **booksLoaded** —— 账套列表**问过了没有**。
 *     列表还没拉回来时 books 是空的，那是「还没问」，不是「没有」。
 *     照着空数组直接判，会把**有**账套的用户也踢回账套管理，而且是在他刚打开
 *     一个深链接的那一瞬间 —— 最让人莫名其妙的那种错。
 *
 *  3. **bookCount** —— 真的一个账套都没有。
 *
 * 三条同时成立才送回去。少任何一条，这条判断都会在某个真实场景里错。
 */
export function needsBookRedirect({ requiresBook = false, booksLoaded = false, bookCount = 0 } = {}) {
  return Boolean(requiresBook) && Boolean(booksLoaded) && Number(bookCount) === 0
}
