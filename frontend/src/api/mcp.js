import { http } from './client'

/**
 * **自己名下**的 MCP 密钥（个人资料页那一块）。
 *
 * **这里的每个接口都只动「本人」的密钥**：请求体里**没有「改谁」这个字段**
 * —— 目标永远是令牌对应的那个人。所以不存在「改到别人头上」的可能，
 * 也不必再问一句「你是不是管理员」。
 *
 * 与管理面（`/api/system/mcp-tokens`，给管理员用的）写的是**同一张表**、
 * **同一套权限语义**：令牌绑一个用户，那个用户能读哪些账套，这枚密钥就能
 * 读哪些账套（可见性 100% 来自后端的用户-账套授权表）。
 *
 * **两个动词别混用**：管理面那侧叫「吊销」（标记失效、记录留着，因为轮换
 * 要用「已吊销但还在宽限期内」这个状态），本人这一侧叫「删除」—— 那一行
 * 从此不存在。
 */

/**
 * 列出自己名下的 MCP 密钥。
 *
 * **不进应用级缓存**：这是典型的「写完立刻读」页面 —— 生成一枚、删掉一枚
 * 之后要立刻看到新的那一屏。缓存层对 `/system/*` 一律不缓存，MCP 密钥这一
 * 路同理（见 `client.js` 的 `canCacheGet`）。
 */
export const listMyTokens = () => http.get('/mcp-tokens').then(r => r.data)

/**
 * 生成一枚属于自己的 MCP 密钥。
 *
 * **必须带当前密码** —— MCP 密钥**永不过期**，是一枚永久读凭据；少了这一道
 * 关，一枚被偷走的会话令牌就能替本人铸出一枚永久密钥，而它不随登出或改密
 * 失效。后端验的就是这个字段。
 *
 * **明文只在这一次响应里返回** —— 之后谁也拿不回来（库里只有 sha256 摘要）。
 * 所以界面必须**当场把它显示出来并让人抄走**，没有「下次再来看」这回事。
 */
export const createMyToken = (payload) =>
  http.post('/mcp-tokens', payload).then(r => r.data)

/**
 * **删掉**一枚。**立即生效** —— 下一次调用就 401。
 *
 * **物理删除**：那一行从此不存在，界面上也不再留一条「已吊销」的旧记录。
 * 与管理面那个「吊销」（标记失效、记录留着）不是同一件事。
 *
 * **不挂再验证闸门**：密钥被盗时要能立刻处置，而那时人可能正处在
 * 「没有当前密码」的状态上 —— 给安全阀加锁是把安全阀焊死。
 */
export const deleteMyToken = (id) =>
  http.delete(`/mcp-tokens/${id}`).then(r => r.data)

/**
 * 一次性**删掉**自己名下**全部**密钥（任何状态都删）。
 *
 * 这是「改密后的标准处置」：MCP 密钥不会随改密自动失效（这是产品决定的，
 * 见架构文档 §11.15 —— 把取舍摆在明面上，而不是让它悄悄发生），所以这条
 * 明面上的处置必须由本人自己来点。
 */
export const deleteAllMyTokens = () =>
  http.delete('/mcp-tokens').then(r => r.data)
